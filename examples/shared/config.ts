// ---------------------------------------------------------------------------
// Environment
// ---------------------------------------------------------------------------

export type Network = "preprod" | "preview" | "mainnet" | "yaci";

export function getEnv(key: string, required = true): string {
  const val = process.env[key];
  if (!val && required) {
    console.error(`Missing required env var: ${key}`);
    console.error("Copy .env.example to .env and fill in your values.");
    process.exit(1);
  }
  return val ?? "";
}

export function getNetwork(): Network {
  return (getEnv("NETWORK", false) || "preprod") as Network;
}

export function isYaci(): boolean {
  return getNetwork() === "yaci";
}

async function resolveChain(): Promise<Chain> {
  const n = getNetwork();
  if (n === "yaci") return getYaciChain();
  if (n === "preview") return previewChain;
  if (n === "mainnet") return mainnetChain;
  return preprodChain;
}

// ---------------------------------------------------------------------------
// Evolution SDK Client
// ---------------------------------------------------------------------------

export async function createSigningClient(mnemonic?: string) {
  const chain = await resolveChain();
  const seed = mnemonic || getEnv("WALLET_MNEMONIC");

  if (isYaci()) {
    const provider = getEnv("YACI_PROVIDER", false) || "kupmios";
    if (provider === "blockfrost") {
      const baseUrl = getEnv("BLOCKFROST_URL", false) || "http://localhost:8080/api/v1";
      return evoClient(chain)
        .withBlockfrost({ projectId: "dummy", baseUrl })
        .withSeed({ mnemonic: seed });
    }
    const kupoUrl = getEnv("KUPO_URL", false) || "http://localhost:1442";
    const ogmiosUrl = getEnv("OGMIOS_URL", false) || "http://localhost:1337";
    return evoClient(chain)
      .withKupmios({ kupoUrl, ogmiosUrl })
      .withSeed({ mnemonic: seed });
  }

  const network = getNetwork();
  const projectId = getEnv("BLOCKFROST_PROJECT_ID");
  const baseUrl =
    getEnv("BLOCKFROST_URL", false) ||
    `https://cardano-${network}.blockfrost.io/api/v0`;

  return evoClient(chain)
    .withBlockfrost({ projectId, baseUrl })
    .withSeed({ mnemonic: seed });
}

export async function createSecondClient() {
  const second = getEnv("SECOND_WALLET_MNEMONIC", false);
  if (!second) return null;
  return createSigningClient(second);
}

type SigningClient = Awaited<ReturnType<typeof createSigningClient>>;

export async function getWalletAddress(client: SigningClient): Promise<string> {
  const addr = await client.address();
  return EvoAddress.toBech32(addr);
}

export function getAdminPkh(address: string): string {
  return paymentCredentialHash(address);
}


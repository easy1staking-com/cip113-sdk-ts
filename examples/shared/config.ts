/**
 * Load CIP-113 standard deployment params from a JSON file matching the current network.
 * Files: deployment-preprod.json, deployment-preview.json, deployment-mainnet.json,
 * deployment-yaci.json (generated by bafin/00-deploy-standard.ts).
 */
export function loadDeployment(): DeploymentParams {
  const network = getNetwork();
  const fullPath = resolve(__dirname, `deployment-${network}.json`);
  return JSON.parse(readFileSync(fullPath, "utf-8"));
}

export function getTokenName(): string {
  const custom = getEnv("TOKEN_NAME", false);
  if (custom) return custom;
  // Generate a unique name per run so repeated runs don't collide
  const ts = Date.now().toString(36).slice(-4).toUpperCase();
  return `DEMO-${ts}`;
}

/**
 * Check if a stake address is registered on-chain.
 * On public networks: queries Blockfrost.
 * On Yaci: queries the Yaci Store Blockfrost-compatible API directly.
 */
export async function checkStakeRegistration(stakeAddress: string): Promise<boolean> {
  const baseUrl = isYaci()
    ? getEnv("BLOCKFROST_URL", false) || "http://localhost:8080/api/v1"
    : getEnv("BLOCKFROST_URL", false) ||
      `https://cardano-${getNetwork()}.blockfrost.io/api/v0`;

  const headers: Record<string, string> = {};
  if (!isYaci()) {
    headers.project_id = getEnv("BLOCKFROST_PROJECT_ID");
  }

  try {
    const res = await fetch(`${baseUrl}/accounts/${stakeAddress}`, { headers });
    return res.ok; // 200 = registered, 404 = not registered
  } catch {
    return false;
  }
}
